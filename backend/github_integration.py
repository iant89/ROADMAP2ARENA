def poll_seconds() -> int:
    try:
        return max(30, int(os.environ.get("R2A_GITHUB_POLL_SECONDS") or 60))
    except ValueError:
        return 60


# ------------------------------------------------------------------ helpers
def slugify(text: str, fallback: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")[:40].strip("-")
    return slug or fallback


def defaults_for(job: dict, steps: list[dict]) -> dict:
    slug = slugify(job.get("title") or "", f"job-{job['id'][:8]}")
    title = job.get("title") or f"ROADMAP2ARENA job {job['id'][:8]}"
    checklist = "\n".join(f"- [{'x' if s['status'] == 'done' else ' '}] Step {s['index']}: {s['title']}" for s in steps)
    body = (f"Generated by ROADMAP2ARENA from job `{job['id']}` "
            f"({job.get('steps_done', 0)}/{job.get('step_total', len(steps))} steps done, model `{job.get('model')}`).\n\n"
            f"## Steps\n{checklist}\n")
    roadmap = (job.get("roadmap_md") or "").strip()
    if roadmap:
        body += f"\n<details><summary>Roadmap</summary>\n\n{roadmap}\n\n</details>\n"
    return {"repo_name": slug, "branch": f"r2a/{slug}", "pr_title": title, "pr_body": body[:PR_BODY_MAX]}


def _allowed_hosts() -> set[str]:
    host = urlparse(ghc.api_url()).hostname or ""
    return {"github.com"} if host == "api.github.com" else {host}


def check_clone_url(url: str) -> str:
    """Only push to GitHub over https (local paths are allowed for tests via an env flag)."""
    p = urlparse(url or "")
    if p.scheme == "https" and p.hostname in _allowed_hosts():
        return url
    if os.environ.get("R2A_GITHUB_ALLOW_FILE_REMOTES") == "1" and (p.scheme == "file" or (url or "").startswith("/")):
        return url
    raise GitHubError(502, f"GitHub returned an unexpected clone URL ({p.scheme or 'no scheme'}://{p.hostname or ''})")


def auth_env(login: str, token: str, host: str) -> dict:
    """http.<host>.extraHeader via GIT_CONFIG_* env vars: not in argv (ps), the URL or .git/config, and
    only sent to that host. The first (empty) value resets any inherited extraHeader list."""
    basic = base64.b64encode(f"{login}:{token}".encode()).decode()
    key = f"http.{host}.extraHeader"
    return {"GIT_CONFIG_COUNT": "3", "GIT_CONFIG_KEY_0": key, "GIT_CONFIG_VALUE_0": "",
            "GIT_CONFIG_KEY_1": key, "GIT_CONFIG_VALUE_1": f"Authorization: Basic {basic}",
            "GIT_CONFIG_KEY_2": "credential.helper", "GIT_CONFIG_VALUE_2": "", "GIT_TERMINAL_PROMPT": "0"}


def classify_push(output: str) -> str:
    low = output.lower()
    if "non-fast-forward" in low or "fetch first" in low or "stale info" in low or "[rejected]" in low:
        return "non_fast_forward"
    if "workflow" in low and ("scope" in low or "permission" in low):
        return "workflow_permission"
    if "could not read username" in low or "authentication failed" in low or "invalid username or token" in low:
        return "auth"
    if "repository not found" in low:
        return "not_found"
    if ("permission to" in low and "denied" in low) or "error: 403" in low or "returned error: 403" in low:
        return "forbidden"
    if "gh013" in low or "protected branch" in low or "rule violations" in low or "gh006" in low:
        return "rules"
    if "timed out" in low:
        return "timeout"
    return "failed"


def push_status(kind: str, branch: str) -> tuple[int, str]:
    return {
        "non_fast_forward": (409, f"The branch '{branch}' already exists on GitHub with different commits. Choose another "
                                  "branch name - ROADMAP2ARENA never force-pushes."),
        "workflow_permission": (403, "Pushing .github/workflows files needs the 'workflow' scope (classic) or "
                                     "'Workflows: write' (fine-grained)."),
        "auth": (401, "GitHub rejected the token during git push - reconnect GitHub in Settings."),
        "not_found": (404, "git push: repository not found, or the token has no access to it."),
        "forbidden": (403, "GitHub refused the push - the token has no write access to this repository "
                           "(classic: 'repo' scope; fine-grained: Contents read/write)."),
        "rules": (409, f"The branch '{branch}' is protected by branch protection / repository rules - choose another "
                       "branch name."),
        "timeout": (504, f"git push timed out after {PUSH_TIMEOUT}s."),
        "failed": (502, "git push failed."),
    }[kind]


def push_sync(root: str, url: str, branch: str, token: str, login: str = "x-access-token",
              timeout: float = PUSH_TIMEOUT) -> None:
    p = urlparse(url)
    host = f"{p.scheme}://{p.hostname}{f':{p.port}' if p.port else ''}/" if p.scheme in ("http", "https") else "https://github.com/"
    env = auth_env(login or "x-access-token", token, host)
    secrets = (token, env["GIT_CONFIG_VALUE_1"].split()[-1])  # the token and its base64 form
    try:
        proc = git_cli.run(root, "push", "--porcelain", "--no-verify", "--", url, f"HEAD:refs/heads/{branch}",
                           env=env, timeout=timeout, check=False)
    except git_cli.GitError as exc:
        out = redact(f"{exc} {getattr(exc, 'stderr', '') or ''}", *secrets)
        code, hint = push_status(classify_push(out), branch)
        raise GitHubError(code, f"{hint} git: {out.strip()[-400:]}") from None
    if proc.returncode == 0:
        return
    out = redact(proc.stderr.decode("utf-8", "replace") + proc.stdout.decode("utf-8", "replace"), *secrets).strip()
    code, hint = push_status(classify_push(out), branch)
    raise GitHubError(code, f"{hint} git: {out[-400:] or f'exit {proc.returncode}'}")


def _http_error(e: GitHubError) -> HTTPException:
    headers = {"Retry-After": str(e.retry_after)} if e.retry_after else None
    return HTTPException(status_code=e.status, detail=e.message, headers=headers)


async def _token_or_409(db) -> str:
    token = await ghc.get_token(db)
    if not token:
        err = ghc.public(await ghc.get_doc(db)).get("token_error")
        raise HTTPException(status_code=409, detail=err or "GitHub is not connected - connect it in Settings > GitHub")
    return token


def _repo_summary(r: dict) -> dict:
    perms = r.get("permissions") or {}
    return {"full_name": r.get("full_name"), "name": r.get("name"), "owner": (r.get("owner") or {}).get("login"),
            "private": bool(r.get("private")), "default_branch": r.get("default_branch"),
            "html_url": r.get("html_url"), "description": r.get("description"),
            "can_push": bool(perms.get("push", perms.get("admin", False))), "updated_at": r.get("updated_at")}


# ------------------------------------------------------------------ core push
class PushRequest(BaseModel):
    mode: str = Field("new", pattern="^(new|existing)$")
    repo_name: str | None = None          # mode=new
    private: bool = True                  # mode=new
    description: str | None = Field(None, max_length=350)
    repo_full_name: str | None = None     # mode=existing, "owner/name"
    branch: str | None = None
    open_pr: bool = False
    pr_base: str | None = None
    pr_title: str | None = Field(None, max_length=256)
    pr_body: str | None = Field(None, max_length=PR_BODY_MAX)


async def push_job(db, job_id: str, body: PushRequest, source: str = "manual") -> dict:
    """Push the job repo to GitHub. Raises GitHubError / HTTPException with clear messages."""
    token = await _token_or_409(db)
    job = await db.jobs.find_one({"id": job_id}, {"_id": 0, "log": 0})
    if not job:
        raise HTTPException(status_code=404, detail=f"Job {job_id} not found")
    if job["status"] == "running":
        raise HTTPException(status_code=409, detail="The job is running - wait until it finishes (or stop it), then push")
    steps = await db.steps.find({"job_id": job_id}, {"_id": 0, "index": 1, "title": 1, "status": 1}).sort("index", 1).to_list(None)
    d = defaults_for(job, steps)
    branch = (body.branch or d["branch"]).strip()
    if not git_cli.valid_branch(branch):
        raise HTTPException(status_code=422, detail=f"'{branch}' is not a valid branch name")
    if body.mode == "new":
        name = (body.repo_name or d["repo_name"]).strip()
        if not ghc.REPO_NAME_RE.match(name) or name in (".", "..") or name.lower().endswith(".git"):
            raise HTTPException(status_code=422, detail="Repository name may only contain letters, digits, '.', '-' "
                                                        "and '_' (max 100) and must not end in .git")
        if body.open_pr:
            raise HTTPException(status_code=422, detail="A new repository has no base branch to open a pull request "
                                                        "against - push it first, then open PRs on later pushes")
    else:
        full = (body.repo_full_name or "").strip()
        if not ghc.FULL_NAME_RE.match(full):
            raise HTTPException(status_code=422, detail="repo_full_name must look like owner/repository")
    if body.pr_base is not None and body.pr_base.strip() and not git_cli.valid_branch(body.pr_base.strip()):
        raise HTTPException(status_code=422, detail=f"'{body.pr_base}' is not a valid base branch name")

    try:
        synced = await git_integration.sync_job(db, job_id)
    except git_cli.GitError as exc:
        raise HTTPException(status_code=500, detail=f"Could not prepare the local repository: {exc}")
    repo_doc = synced["repo"]
    if not repo_doc.get("head"):
        raise HTTPException(status_code=409, detail="The job's repository has no commits yet - nothing to push")
    root = repos.abs_path(repo_doc)

    login = ((await ghc.get_doc(db)) or {}).get("username") or "x-access-token"
    async with GitHub(token) as gh:
        created = False
        if body.mode == "new":
            try:
                resp = await gh.request("POST", "/user/repos", "create the repository", json={
                    "name": name, "private": body.private, "auto_init": False,
                    "description": body.description or f"Generated by ROADMAP2ARENA: {job.get('title') or ''}"[:350]})
            except GitHubError as e:
                if e.gh_status == 422 and "already exists" in e.message.lower():
                    raise GitHubError(409, f"A repository named '{name}' already exists in your account - choose "
                                           "another name or pick it under 'Existing repository'.")
                raise
            gh_repo, created = resp.json(), True
        else:
            gh_repo = (await gh.request("GET", f"/repos/{full}", f"find the repository {full}")).json()
            perms = gh_repo.get("permissions") or {}
            if perms and not (perms.get("push") or perms.get("admin")):
                raise GitHubError(403, f"Your token has no push access to {full}.")
        url = check_clone_url(gh_repo.get("clone_url", ""))
        html = gh_repo.get("html_url") or ""
        async with repos.lock_for(root):
            head = git_cli.out(root, "rev-parse", "HEAD").strip()
            await asyncio.to_thread(push_sync, root, url, branch, token, login)

        pr, pr_error = None, None
        if body.open_pr:
            base = (body.pr_base or "").strip() or gh_repo.get("default_branch") or "main"
            if base == branch:
                pr_error = "The base branch is the pushed branch - nothing to compare"
            else:
                try:
                    r = await gh.request("POST", f"/repos/{gh_repo['full_name']}/pulls", "open the pull request", json={
                        "title": (body.pr_title or d["pr_title"])[:256], "body": body.pr_body if body.pr_body is not None else d["pr_body"],
                        "head": branch, "base": base})
                    p = r.json()
                    pr = {"number": p.get("number"), "html_url": p.get("html_url"), "existing": False, "base": base,
                          "state": p.get("state", "open")}
                except GitHubError as e:
                    low = e.message.lower()
                    if "already exists" in low:
                        owner = gh_repo["full_name"].split("/")[0]
                        try:
                            r = await gh.request("GET", f"/repos/{gh_repo['full_name']}/pulls", "find the open pull request",
                                                 params={"head": f"{owner}:{branch}", "state": "open"})
                            items = r.json()
                            if items:
                                pr = {"number": items[0].get("number"), "html_url": items[0].get("html_url"),
                                      "existing": True, "base": items[0].get("base", {}).get("ref", base),
                                      "state": items[0].get("state", "open")}
                        except GitHubError:
                            pass
                        if not pr:
                            pr_error = "A pull request for this branch already exists"
                    elif "no history in common" in low:
                        pr_error = (f"Pushed, but no PR: '{branch}' has no history in common with '{base}' (the job "
                                    "repository started from scratch). Open a PR manually after merging histories.")
                    elif "no commits between" in low:
                        pr_error = f"Pushed, but no PR: there are no commits between '{base}' and '{branch}'."
                    elif e.gh_status == 422 and "base" in low:
                        pr_error = f"Pushed, but no PR: the base branch '{base}' does not exist."
                    else:
                        pr_error = f"Pushed, but the pull request failed: {e.message}"

    full_name = gh_repo.get("full_name")
    ts = now_iso()
    result = {
        "pushed": True, "source": source, "pushed_at": ts, "branch": branch, "head": head,
        "commit_count": repo_doc.get("commit_count"),
        "repo": {"full_name": full_name, "html_url": html, "private": bool(gh_repo.get("private")), "created": created},
        "branch_url": f"{html}/tree/{quote(branch, safe='/')}" if html else None,
        "commit_url": f"{html}/commit/{head}" if html else None,
        "pr": pr, "pr_error": pr_error,
    }
    remote = {"provider": "github", "full_name": full_name, "html_url": html, "clone_url": url, "branch": branch,
              "private": bool(gh_repo.get("private")), "pushed_head": head, "pushed_at": ts,
              "pr_url": pr["html_url"] if pr else None, "pr_number": pr["number"] if pr else None}
    await db.repos.update_one({"id": repo_doc["id"]}, {"$pull": {"remotes": {"provider": "github", "full_name": full_name, "branch": branch}}})
    await db.repos.update_one({"id": repo_doc["id"]}, {"$push": {"remotes": remote}})
    await db.jobs.update_one({"id": job_id}, {"$set": {"github": result}})
    what = "auto-pushed" if source == "auto" else "pushed"
    await append_log(db, job_id, "ok", f"GitHub: {what} {repo_doc.get('commit_count')} commits to {full_name} "
                                       f"branch {branch}{' (new repository)' if created else ''}")
    if pr:
        await append_log(db, job_id, "ok", f"GitHub: pull request #{pr['number']}{' (already open)' if pr['existing'] else ''} {pr['html_url']}")
    if pr_error:
        await append_log(db, job_id, "warn", f"GitHub: {pr_error}")
    await upsert_watch(db, job_id, full_name, html, branch, head, pr)
    await _notify(db, "github_pushed", job_id, f"{'Auto-pushed' if source == 'auto' else 'Pushed'} "
                  f"{repo_doc.get('commit_count')} commits to {full_name}:{branch} ({head[:7]})", result["branch_url"])
    if pr and not pr["existing"]:
        await _notify(db, "github_pr_opened", job_id, f"Opened PR #{pr['number']} in {full_name}", pr["html_url"])
    return result


async def on_job_finished(db, job_id: str, status: str) -> None:
    """Auto-push on completion (if enabled): to the job's last pushed repo/branch, else a new repo."""
    if status != "done":
        return
    doc = await ghc.get_doc(db)
    if not doc or not (doc.get("auto_push") or {}).get("enabled") or not await ghc.get_token(db):
        return
    job = await db.jobs.find_one({"id": job_id}, {"_id": 0, "github": 1, "title": 1})
    last = (job or {}).get("github")
    if last and last.get("repo", {}).get("full_name"):
        req = PushRequest(mode="existing", repo_full_name=last["repo"]["full_name"], branch=last["branch"])
    else:
        name = slugify((job or {}).get("title") or "", "r2a")[:60] + f"-{job_id[:6]}"
        req = PushRequest(mode="new", repo_name=name, private=bool(doc["auto_push"].get("private", True)))
    try:
        await push_job(db, job_id, req, source="auto")
    except (GitHubError, HTTPException) as exc:
        msg = exc.message if isinstance(exc, GitHubError) else exc.detail
        logger.warning("auto-push of job %s failed: %s", job_id, msg)
        await append_log(db, job_id, "warn", f"GitHub: auto-push failed - {msg}")
    except Exception as exc:  # noqa: BLE001 - never break anything after a job
        logger.exception("auto-push of job %s crashed", job_id)
        await append_log(db, job_id, "warn", f"GitHub: auto-push failed - {type(exc).__name__}")


