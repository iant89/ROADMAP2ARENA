_poll_lock = asyncio.Lock()
_poller: asyncio.Task | None = None
_wake: asyncio.Event | None = None
_paused_until = 0.0
_pause_reason: str | None = None


def _wake_poller() -> None:
    if _wake is not None:
        _wake.set()


def resume_polling() -> None:
    """A new token: lift an auth/rate-limit pause and poll soon."""
    global _paused_until, _pause_reason
    _paused_until, _pause_reason = 0.0, None
    _wake_poller()


async def upsert_watch(db, job_id: str, full_name: str, html_url: str, branch: str, head: str, pr: dict | None) -> None:
    now = datetime.now(timezone.utc)
    await db.github_watches.update_one(
        {"job_id": job_id, "full_name": full_name, "branch": branch},
        {"$set": {"html_url": html_url, "head_sha": head, "pr_number": pr["number"] if pr else None, "active": True,
                  "etags": {}, "state": {"pr_state": pr.get("state", "open") if pr else None, "ci": None, "src": {}},
                  "last_error": None, "pushed_at": now.isoformat(), "expires_at": (now + timedelta(days=WATCH_DAYS)).isoformat(),
                  "updated_at": now_iso()},
         "$setOnInsert": {"created_at": now_iso()}}, upsert=True)
    _wake_poller()


FAILED = {"failure", "timed_out", "action_required", "cancelled", "startup_failure", "error"}


def ci_state(src: dict) -> str:
    """Aggregate {'status': combined state, 'status_count', 'checks': [conclusion|None]} into none|pending|success|failure."""
    states = []
    if src.get("status_count"):
        states.append(src.get("status"))
    states += [("pending" if c is None else "failure" if c in FAILED else "success") for c in src.get("checks") or []]
    if not states:
        return "none"
    if "failure" in states or "error" in states:
        return "failure"
    return "pending" if "pending" in states else "success"


async def poll_watch(gh: GitHub, w: dict) -> list[tuple[str, str, str]]:
    """Poll one watch with conditional requests; returns [(event, message, link)] and updates w in place."""
    full = w["full_name"]
    base, et, st, events = f"/repos/{full}", dict(w.get("etags") or {}), dict(w.get("state") or {}), []
    html = w.get("html_url") or f"https://github.com/{full}"
    changed, data, et["branch"] = await gh.get_cond(f"{base}/branches/{GitHub.ref(w['branch'])}", et.get("branch"),
                                                    f"read branch {w['branch']} of {full}")
    if changed and data and data.get("commit", {}).get("sha") and data["commit"]["sha"] != w["head_sha"]:
        w["head_sha"] = data["commit"]["sha"]
        st.update(ci=None, src={})
        for k in ("status", "checks_api", "actions_api"):
            et.pop(k, None)
        events.append(("github_pushed", f"New commits on {full}:{w['branch']} ({w['head_sha'][:7]})",
                       f"{html}/commit/{w['head_sha']}"))
    if w.get("pr_number") and st.get("pr_state") not in ("merged", "closed"):
        changed, pr, et["pr"] = await gh.get_cond(f"{base}/pulls/{w['pr_number']}", et.get("pr"),
                                                  f"read pull request #{w['pr_number']} of {full}")
        if changed and pr:
            new = "merged" if pr.get("merged") else pr.get("state")  # `merged`, never merge_commit_sha (gone in 2026-03-10)
            if new != st.get("pr_state"):
                st["pr_state"] = new
                if new == "merged":
                    events.append(("github_pr_merged", f"PR #{w['pr_number']} merged in {full}", pr.get("html_url")))
                elif new == "closed":
                    events.append(("github_pr_closed", f"PR #{w['pr_number']} in {full} closed without merging",
                                   pr.get("html_url")))
    if st.get("ci") not in ("success", "failure"):
        src, sha = dict(st.get("src") or {}), w["head_sha"]
        changed, data, et["status"] = await gh.get_cond(f"{base}/commits/{sha}/status", et.get("status"),
                                                        "read the commit status")
        if changed and data:
            src.update(status=data.get("state"), status_count=data.get("total_count", 0))
        for api, path, key, params in (("checks_api", f"{base}/commits/{sha}/check-runs", "check_runs", {"per_page": 100}),
                                       ("actions_api", f"{base}/actions/runs", "workflow_runs", {"head_sha": sha, "per_page": 50})):
            if st.get(api) == "unavailable":
                continue
            try:
                changed, data, et[api] = await gh.get_cond(path, et.get(api), "read CI results", params)
            except GitHubError as e:
                if e.kind not in ("forbidden", "not_found"):
                    raise
                st[api] = "unavailable"  # e.g. a fine-grained PAT without Checks access: use Actions runs instead
                continue
            if changed and data:
                src["checks"] = [r.get("conclusion") if r.get("status") == "completed" else None for r in data.get(key, [])]
            if src.get("checks"):
                break  # check runs already include GitHub Actions; workflow runs are only the fallback
        st["src"], new = src, ci_state(src)
        if new in ("success", "failure") and new != st.get("ci"):
            ok = new == "success"
            events.append(("github_checks_passed" if ok else "github_checks_failed",
                           f"Checks {'passed' if ok else 'failed'} on {full}:{w['branch']} ({sha[:7]})", f"{html}/commit/{sha}"))
        st["ci"] = new
    w["etags"], w["state"] = et, st
    now = datetime.now(timezone.utc)
    pr_done = not w.get("pr_number") or st.get("pr_state") in ("merged", "closed")
    fresh = datetime.fromisoformat(w["pushed_at"]) > now - NO_CI_GRACE
    ci_done = st.get("ci") in ("success", "failure") or (st.get("ci") == "none" and not fresh)  # CI may start late
    w["active"] = datetime.fromisoformat(w["expires_at"]) > now and not (pr_done and ci_done)
    return events


async def poll_once(db=None) -> dict:
    """One pass over the active watches, serially (GitHub asks integrations not to send concurrent requests)."""
    global _paused_until, _pause_reason
    db = db if db is not None else default_db
    if time.time() < _paused_until:
        return {"skipped": _pause_reason or "paused", "resume_in": int(_paused_until - time.time()), "watches": 0,
                "notifications": 0}
    token = await ghc.get_token(db)
    if not token:
        return {"skipped": "not_connected", "watches": 0, "notifications": 0}
    async with _poll_lock:
        watches = await db.github_watches.find({"active": True}).sort("updated_at", -1).to_list(100)
        sent, polled, now = 0, 0, datetime.now(timezone.utc)
        async with GitHub(token) as gh:
            for w in watches:
                if datetime.fromisoformat(w["expires_at"]) < now:
                    await db.github_watches.update_one({"_id": w["_id"]}, {"$set": {"active": False}})
                    continue
                try:
                    events, err = await poll_watch(gh, w), None
                except GitHubError as e:
                    if e.kind in ("rate_limited", "auth"):
                        _paused_until = time.time() + ((e.retry_after or 60) if e.kind == "rate_limited" else 600)
                        _pause_reason = e.kind
                        logger.warning("GitHub polling paused (%s): %s", e.kind, e.message)
                        await db.github_watches.update_one({"_id": w["_id"]}, {"$set": {"last_error": e.message}})
                        break
                    events, err = [], e.message
                polled += 1
                await db.github_watches.update_one({"_id": w["_id"]}, {"$set": {
                    "head_sha": w["head_sha"], "etags": w.get("etags", {}), "state": w.get("state", {}),
                    "active": w.get("active", True), "last_error": err, "last_polled_at": now_iso()}})
                for event, message, link in events:
                    await _notify(db, event, w["job_id"], message, link)
                    sent += 1
            remaining, reset = gh.rate.get("remaining"), gh.rate.get("reset")
            if remaining is not None and remaining.isdigit() and int(remaining) < RATE_FLOOR and (reset or "").isdigit():
                _paused_until, _pause_reason = float(reset), "rate_low"
                logger.warning("GitHub polling paused until the rate limit resets (%s calls left)", remaining)
    return {"watches": polled, "notifications": sent}


async def _loop() -> None:
    while True:
        try:
            await poll_once()
        except asyncio.CancelledError:
            raise
        except Exception:  # noqa: BLE001 - keep polling
            logger.exception("GitHub poll failed")
        try:
            await asyncio.wait_for(_wake.wait(), timeout=poll_seconds())
        except asyncio.TimeoutError:
            pass
        _wake.clear()


def start_poller() -> None:
    global _poller, _wake
    if _poller is None or _poller.done():
        _wake = asyncio.Event()
        _poller = asyncio.create_task(_loop(), name="github-poller")


async def stop_poller() -> None:
    global _poller
    if _poller:
        _poller.cancel()
        try:
            await _poller
        except asyncio.CancelledError:
            pass
        _poller = None


