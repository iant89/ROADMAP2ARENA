"""Push a job's local git repo to GitHub (new or existing repo), optionally open a PR.

Routes:
  GET    /api/github                 connection status (never the token)
  PUT    /api/github/token {token}   validate via GET /user and store (server-side, Mongo)
  DELETE /api/github                 disconnect (token removed)
  PUT    /api/github/settings        {auto_push: {enabled, private}, oauth_client_id}
  POST   /api/github/oauth/start     OAuth device flow: get a user code + verification URL
  POST   /api/github/oauth/poll      exchange the device code (call every `interval` s)
  POST   /api/github/oauth/cancel    abandon the pending device flow

OAuth and personal access tokens are mutually exclusive: connecting one while the other is
active (or while a device flow is pending) is a 409; disconnect first.
  GET    /api/github/repos?q=        the user's repositories (searchable)
  GET    /api/jobs/{id}/github       defaults for the push dialog + last push + watches
  POST   /api/jobs/{id}/github/push  push (and optionally open a PR)
  GET    /api/github/watches         what the poller is watching
  POST   /api/github/poll            poll GitHub now (otherwise every R2A_GITHUB_POLL_SECONDS)

Never force-pushes: a branch that exists on GitHub with different history is reported as a
conflict. The token reaches git only as an http.<host>.extraHeader passed through GIT_CONFIG_*
environment variables of one git process - never argv, the remote URL or .git/config - and all
git output is redacted. After a push a watch polls the branch, PR and CI with conditional
requests and emits github_* notifications (no public URL or webhook needed). The poller lives
in-process: keep uvicorn at --workers 1.
"""
