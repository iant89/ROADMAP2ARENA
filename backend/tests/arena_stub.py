TURNS = [_turn_1, _turn_2, _turn_3]


def _completion(model: str, content: str, prompt_chars: int) -> dict:
    return {
        "id": f"chatcmpl-{uuid.uuid4().hex[:12]}",
        "object": "chat.completion",
        "created": int(time.time()),
        "model": model,
        "choices": [{
            "index": 0,
            "message": {"role": "assistant", "content": content},
            "finish_reason": "stop",
        }],
        "usage": {"prompt_tokens": prompt_chars // 4, "completion_tokens": len(content) // 4,
                  "total_tokens": (prompt_chars + len(content)) // 4},
    }


def _error(status: int, message: str) -> JSONResponse:
    return JSONResponse(status_code=status, content={"error": {"message": message, "type": "stub_error", "code": status}})


@app.get("/v1/models")
async def models():
    return {"object": "list", "data": [{"id": m, "object": "model"} for m in ("gpt-4o", "stub-503", "stub-slow")]}


@app.post("/v1/chat/completions")
async def chat(request: Request):
    body = await request.json()
    model = body.get("model", "")
    messages = body.get("messages", [])
    turn = sum(1 for m in messages if m.get("role") == "user")
    if model == "stub-503":
        return _error(503, "no upstream session token available")
    if model.startswith("stub-503-at-") and model.rsplit("-", 1)[-1].isdigit() and turn == int(model.rsplit("-", 1)[-1]):
        return _error(503, "no upstream session token available")
    if model == "stub-slow":
        await asyncio.sleep(SLOW_SECONDS)
    content = TURNS[(max(turn, 1) - 1) % len(TURNS)]()
    prompt_chars = sum(len(m.get("content") or "") for m in messages)
    return _completion(model, content, prompt_chars)
