"""Local stand-in for arena2api used in tests (NOT the real gateway).

Serves POST /v1/chat/completions in OpenAI format with canned fenced code
blocks. The response depends on how many user turns are in the request
history, so step N of a job gets canned reply N (cycled).

Magic model names:
  stub-503   -> HTTP 503 (simulates arena2api without a session token)
  stub-slow  -> sleeps STUB_SLOW_SECONDS (default 5) per call, for 409 testing
  stub-503-at-N -> HTTP 503 on the N-th user turn only

Run: /app/venv/bin/uvicorn tests.arena_stub:app --host 127.0.0.1 --port 9090
(from /app/backend).
"""
from __future__ import annotations

import asyncio
import os
import time
import uuid

from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse

FENCE = "```"
SLOW_SECONDS = float(os.environ.get("STUB_SLOW_SECONDS", "5"))

app = FastAPI(title="arena2api stub")


